const { chromium } = require("playwright-core");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const base = process.env.BASE_URL || "http://127.0.0.1:5186";
const share = process.env.VERCEL_SHARE_URL;
const chrome = process.env.CHROME_PATH || [
  "C:/Program Files/Google/Chrome/Application/chrome.exe",
  "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
].find((candidate) => fs.existsSync(candidate));
const photo = fs.readFileSync(path.join(__dirname, "..", "assets", "hex.png"));

(async () => {
  const browser = await chromium.launch({ headless: true, ...(chrome ? { executablePath: chrome } : {}) });
  try {
    for (const width of [390, 768, 1440]) {
      const context = await browser.newContext({ viewport: { width, height: 900 } });
      const page = await context.newPage();
      if (share) await page.goto(share);
      const errors = [];
      const remote = [];
      page.on("pageerror", (error) => errors.push(error.message));
      await context.route("https://*.supabase.co/**", (route) => { remote.push(route.request().url()); return route.abort(); });
      await context.route("https://*.tile.openstreetmap.org/**", (route) => route.abort());
      page.on("dialog", (dialog) => dialog.accept());
      try {
        await page.goto(base + "/#login");
        await page.getByRole("button", { name: "Entrar como Tutor Local" }).click();
        await page.getByRole("heading", { name: "Minha Área" }).waitFor();
        await page.goto(base + "/#admin");
        await page.getByRole("heading", { name: "Acesso negado" }).waitFor();
        await assert.rejects(page.evaluate(() => window.BPRemoteStore.localAdminSnapshot()), /Administrador Local/);
        await assert.rejects(page.evaluate(() => window.BPRemoteStore.localAdminAction("user", "x", "suspended", "Motivo de teste")), /Administrador Local/);

        await page.goto(base + "/#novo-animal");
        const pet = page.locator("#real-pet-form");
        await pet.locator('[name="name"]').fill("Amora de teste");
        await pet.locator('[name="breed"]').fill("Sem raça definida");
        await pet.locator('[name="pet_photos"]').setInputFiles({ name: "amora.png", mimeType: "image/png", buffer: photo });
        await pet.getByRole("button", { name: "Salvar animal" }).click();
        await page.getByRole("heading", { name: "Amora de teste" }).waitFor();
        const animalId = new URL(page.url()).hash.split("/")[1];
        await page.goto(base + "/#publicar/lost");
        const occurrence = page.locator("#real-occurrence-form");
        await occurrence.locator('[name="pet_id"]').selectOption(animalId);
        await occurrence.locator('[name="city"]').fill("Cuiabá");
        await occurrence.locator('[name="region"]').fill("Centro");
        await occurrence.locator('[name="description"]').fill("Alerta criado para o teste da moderação local.");
        await occurrence.locator('[name="reuse_pet_photos"]').check();
        await occurrence.getByRole("button", { name: "Marcar centro do mapa" }).click();
        await occurrence.locator('[name="location_consent"]').check();
        await occurrence.locator('[name="rights"]').check();
        await occurrence.getByRole("button", { name: "Publicar alerta" }).click();
        await page.getByRole("heading", { name: "Animal desaparecido", exact: true }).waitFor();
        const occurrenceId = new URL(page.url()).hash.split("/")[1];
        await page.getByRole("link", { name: "Denunciar alerta" }).click();
        const report = page.locator("#real-occurrence-report-form");
        await report.locator('[name="category"]').selectOption("false_misleading");
        await report.locator('[name="description"]').fill("Denúncia criada para testar o fluxo administrativo local.");
        await report.getByRole("button", { name: "Enviar denúncia" }).click();
        await page.getByRole("heading", { name: "Animal desaparecido", exact: true }).waitFor();
        await page.goto(base + "/#home");
        await page.locator("[data-occurrence-card]").waitFor();
        await page.goto(base + "/#mapa");
        await page.locator("#map-results-status").getByText("1 ponto desta prévia").waitFor();
        await page.goto(base + "/#minha-conta");
        await page.getByRole("button", { name: "Sair da prévia" }).click();
        await page.getByRole("button", { name: "Entrar como Administrador Local" }).click();
        await page.getByRole("heading", { name: "Administração Local" }).waitFor();
        assert.match(await page.locator(".admin-metrics").innerText(), /Denúncias pendentes/);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
        if (process.env.ADMIN_SCREENSHOT_DIR) {
          fs.mkdirSync(process.env.ADMIN_SCREENSHOT_DIR, { recursive: true });
          await page.screenshot({ path: path.join(process.env.ADMIN_SCREENSHOT_DIR, `dashboard-${width}.png`), fullPage: true });
        }
        await page.getByRole("button", { name: "Abrir opções de acessibilidade" }).click();
        await page.locator("#accessibility-dialog").getByLabel("Escolha de cor").selectOption("dark");
        assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
        await page.keyboard.press("Escape");
        if (process.env.ADMIN_SCREENSHOT_DIR) await page.screenshot({ path: path.join(process.env.ADMIN_SCREENSHOT_DIR, `dashboard-dark-${width}.png`), fullPage: true });
        await page.getByRole("button", { name: "Abrir opções de acessibilidade" }).click();
        await page.locator("#accessibility-dialog").getByLabel("Escolha de cor").selectOption("light");
        await page.keyboard.press("Escape");
        await page.goto(base + "/#admin/usuarios");
        await page.locator('[data-admin-filter="query"]').fill("inexistente");
        await page.getByText("Nenhum usuário corresponde aos filtros.").waitFor();
        await page.locator('[data-admin-filter="query"]').fill("Tutor Local");
        await page.getByRole("link", { name: "Ver detalhes" }).click();
        await page.getByText("Amora de teste").waitFor();
        await page.goto(base + "/#admin/ocorrencias");
        await page.locator('[data-admin-filter="type"]').selectOption("found");
        await page.getByText("Nenhuma ocorrência corresponde aos filtros.").waitFor();
        await page.locator('[data-admin-filter="type"]').selectOption("lost");
        await page.getByRole("link", { name: "Ver detalhes" }).click();
        await page.getByText("Alerta criado para o teste da moderação local.").waitFor();
        await page.goto(base + "/#admin/moderacao");
        await page.getByText("1 denúncia pendente").waitFor();
        if (process.env.ADMIN_SCREENSHOT_DIR) await page.screenshot({ path: path.join(process.env.ADMIN_SCREENSHOT_DIR, `moderacao-${width}.png`), fullPage: true });
        await page.goto(base + "/#admin/denuncias");
        await page.getByRole("link", { name: "Ver detalhes" }).click();
        await page.getByText("Denúncia criada para testar o fluxo administrativo local.").waitFor();
        await page.locator('.local-admin-action[data-decision="resolved"] [name="reason"]').fill("Denúncia aprovada para teste local.");
        await page.locator('.local-admin-action[data-decision="resolved"] button[type="submit"]').click();
        await page.getByText("Decisão registrada no histórico.").waitFor();
        await page.goto(base + "/#home");
        assert.equal(await page.locator("[data-occurrence-card]").count(), 0);
        await page.goto(base + "/#mapa");
        await page.locator("#map-results-status").getByText("0 pontos desta prévia").waitFor();
        await page.goto(`${base}/#pet/${occurrenceId}`);
        await page.getByRole("heading", { name: "Alerta indisponível" }).waitFor();
        await page.goto(`${base}/#admin/ocorrencias/${occurrenceId}`);
        await page.locator('.local-admin-action[data-decision="restore"] [name="reason"]').fill("Publicação restaurada após revisão local.");
        await page.locator('.local-admin-action[data-decision="restore"] button[type="submit"]').click();
        await page.getByText("Publicação restaurada", { exact: true }).waitFor();
        await page.reload();
        await page.getByText("Publicação restaurada", { exact: true }).waitFor();
        await page.goto(base + "/#home");
        await page.locator("[data-occurrence-card]").waitFor();
        await page.goto(base + "/#mapa");
        await page.locator("#map-results-status").getByText("1 ponto desta prévia").waitFor();
        await page.goto(base + "/#admin");
        await page.getByRole("button", { name: "Sair" }).click();
        await page.getByRole("button", { name: "Entrar como Tutor Local" }).click();
        await page.goto(`${base}/#denunciar/${occurrenceId}`);
        const secondReport = page.locator("#real-occurrence-report-form");
        await secondReport.locator('[name="category"]').selectOption("other");
        await secondReport.locator('[name="description"]').fill("Segunda denúncia de teste para verificar a rejeição.");
        await secondReport.getByRole("button", { name: "Enviar denúncia" }).click();
        await page.goto(base + "/#minha-conta");
        await page.getByRole("button", { name: "Sair da prévia" }).click();
        await page.getByRole("button", { name: "Entrar como Administrador Local" }).click();
        await page.goto(base + "/#admin/denuncias");
        await page.getByText("Outro motivo").first().locator("..").getByRole("link", { name: "Ver detalhes" }).click();
        await page.locator('.local-admin-action[data-decision="dismissed"] [name="reason"]').fill("Denúncia rejeitada após análise de teste.");
        await page.locator('.local-admin-action[data-decision="dismissed"] button[type="submit"]').click();
        await page.getByText("Denúncia rejeitada", { exact: true }).waitFor();
        await page.goto(base + "/#home");
        await page.locator("[data-occurrence-card]").waitFor();
        await page.goto(`${base}/#admin/ocorrencias/${occurrenceId}`);
        await page.locator('.local-admin-action[data-decision="hide"] [name="reason"]').fill("Ocultação manual para revisar a publicação.");
        await page.locator('.local-admin-action[data-decision="hide"] button[type="submit"]').click();
        await page.getByText("Publicação ocultada", { exact: true }).waitFor();
        await page.goto(base + "/#home");
        assert.equal(await page.locator("[data-occurrence-card]").count(), 0);
        await page.goto(`${base}/#admin/ocorrencias/${occurrenceId}`);
        await page.locator('.local-admin-action[data-decision="restore"] [name="reason"]').fill("Restauração manual após análise do teste.");
        await page.locator('.local-admin-action[data-decision="restore"] button[type="submit"]').click();
        await page.getByText("Publicação restaurada", { exact: true }).first().waitFor();
        await page.goto(base + "/#admin/usuarios");
        await page.getByRole("link", { name: "Ver detalhes" }).click();
        await page.locator('.local-admin-action[data-decision="suspended"] [name="reason"]').fill("Desativação demonstrativa para verificar a restrição.");
        await page.locator('.local-admin-action[data-decision="suspended"] button[type="submit"]').click();
        await page.getByText("Tutor desativado", { exact: true }).waitFor();
        await assert.rejects(page.evaluate(() => window.BPRemoteStore.createPet({ name: "Inválido" })), /Tutor Local/);
        await page.getByRole("button", { name: "Sair" }).click();
        await page.getByRole("button", { name: "Entrar como Tutor Local" }).click();
        await page.locator("#real-toast").getByText(/Tutor Local está desativado/).waitFor();
        await page.getByRole("button", { name: "Entrar como Administrador Local" }).click();
        await page.goto(base + "/#admin/usuarios");
        await page.getByRole("link", { name: "Ver detalhes" }).click();
        await page.locator('.local-admin-action[data-decision="active"] [name="reason"]').fill("Reativação demonstrativa após a verificação.");
        await page.locator('.local-admin-action[data-decision="active"] button[type="submit"]').click();
        await page.getByText("Tutor ativado", { exact: true }).waitFor();
        await page.reload();
        await page.getByText("Tutor ativado", { exact: true }).waitFor();
        assert.equal(await page.evaluate(() => window.BPSupabase?.configured), false);
        assert.deepEqual(remote, []);
        assert.deepEqual(errors, []);
        console.log(`${width}px: tutor, denúncia, painel, filtros, moderação, feed/mapa, restauração e persistência passaram.`);
      } finally { await context.close(); }
    }
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
